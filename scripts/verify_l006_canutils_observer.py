#!/usr/bin/env python3
"""Verify the original candump observer on an existing Linux SocketCAN link.

The peer frame is generated by python-can only to exercise the observer.  It
is explicitly not a CUTIL send authorization: this script never invokes
``cansend`` and never treats its local observer reservation as a wire grant.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import platform
import subprocess
import sys
import time
from typing import Any

import can


ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from icd_runtime.contract import Contract
from input_simulator.replay_export import ExportBinding
from input_simulator.tool_commands import ToolCommandBuilder
from input_simulator.tool_process import ProcessSupervisor
from input_simulator.tools import ChannelReservations


BASELINE_SHA256 = "22163dc21526ceadd63260b3d5670404a1064c4301e52b2a80edcf41a4fe8a27"


def require_existing_can_interface(interface: str) -> str:
    probe = subprocess.run(("ip", "-details", "link", "show", "dev", interface),
                           text=True, capture_output=True, check=False)
    if probe.returncode != 0:
        raise RuntimeError("an existing Linux CAN interface is required: %s" % interface)
    if "UP" not in probe.stdout:
        raise RuntimeError("CAN interface is not UP: %s" % interface)
    return probe.stdout


def require_executable(value: Path) -> Path:
    path = value.resolve(strict=True)
    if not path.is_file() or not path.stat().st_mode & 0o111:
        raise RuntimeError("an executable candump path is required")
    return path


def sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as source:
        while chunk := source.read(65536):
            digest.update(chunk)
    return digest.hexdigest()


def wait_terminal(worker: ProcessSupervisor, *, timeout_s: float) -> Any:
    deadline = time.monotonic() + timeout_s
    while time.monotonic() < deadline:
        snapshot = worker.poll()
        if snapshot.state != "RUNNING":
            return snapshot
        time.sleep(.005)
    return worker.stop()


def run(interface: str, channel_id: str, candump: Path, output: Path, contract_dir: Path,
        expected_sha256: str) -> Path:
    interface_details = require_existing_can_interface(interface)
    candump = require_executable(candump)
    contract = Contract.load(contract_dir, expected_sha256=expected_sha256)
    reservations = ChannelReservations()
    observer = reservations.reserve("l006-cutil-observer", "CUTIL", (interface,), mode="OBSERVE")
    try:
        plan = ToolCommandBuilder(contract, reservations).observe(
            observer, (ExportBinding(channel_id, interface),))
        command = plan.commands[0].argv
        if (command[0] != "candump" or observer.authorized_to_transmit
                or plan.authorized_to_transmit):
            raise RuntimeError("default observer unexpectedly has send authority")
        executable_command = (str(candump),) + command[1:]

        # The first child proves the supervised start/stop path without sending.
        idle = ProcessSupervisor(executable_command, cwd=ROOT, timeout_ms=2000, stop_timeout_ms=1000)
        idle.start()
        time.sleep(.05)
        idle_snapshot = idle.stop()
        if idle_snapshot.state != "STOPPED" or not idle_snapshot.direct_child_terminal:
            raise RuntimeError("candump did not stop as a bounded direct child")
        idle.close()

        # -n 1 only bounds this observation test; it leaves the formal filters intact.
        receive_command = executable_command[:-1] + ("-n", "1", executable_command[-1])
        receiver = ProcessSupervisor(receive_command, cwd=ROOT, timeout_ms=3000, stop_timeout_ms=1000)
        receiver.start()
        time.sleep(.05)
        frame_id = min(item["can_id"] for item in contract.messages.values() if item["can_id"] is not None)
        payload = bytes(range(64))
        bus = can.Bus(interface="socketcan", channel=interface, fd=True,
                      receive_own_messages=False, ignore_config=True)
        try:
            result = bus.send(can.Message(arbitration_id=frame_id, data=payload,
                                          is_extended_id=False, is_fd=True,
                                          bitrate_switch=True, check=True), timeout=.1)
            if result is not None:
                raise RuntimeError("python-can peer send returned a value")
        finally:
            bus.shutdown()
        receive_snapshot = wait_terminal(receiver, timeout_s=2)
        receiver.close()
        text = receive_snapshot.stdout.decode("ascii", errors="strict")
        # candump prints CANFD_BRS (bit 1) together with CANFD_FDF (bit 4),
        # therefore a received FD/BRS frame is represented as ``##5``.
        expected_frame = "%03X##5" % frame_id
        if (receive_snapshot.state != "EXITED" or receive_snapshot.returncode != 0
                or not receive_snapshot.direct_child_terminal or "(" not in text or ")" not in text
                or interface not in text or expected_frame not in text.upper()
                or payload.hex().upper() not in text.upper()):
            raise RuntimeError("candump did not observe the expected timestamped FD/BRS frame")
    finally:
        reservations.release(observer)

    report = {
        "format": "HIL_L006_CUTIL_VCAN_OBSERVER_1",
        "status": "SOFTWARE_CUTIL_OBSERVER_VERIFIED",
        "execution_host": "Linux %s (%s)" % (platform.release(), platform.machine()),
        "generated_at_utc": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
        "interface": interface,
        "channel_id": channel_id,
        "interface_details": interface_details,
        "candump": str(candump),
        "candump_sha256": sha256_file(candump),
        "python_can_version": can.__version__,
        "default_observer_argv": list(command),
        "bounded_observer_argv": list(receive_command),
        "observer_start_stop": {
            "state": idle_snapshot.state,
            "direct_child_terminal": idle_snapshot.direct_child_terminal,
        },
        "observation": {
            "state": receive_snapshot.state,
            "returncode": receive_snapshot.returncode,
            "stdout": text,
            "frame_id": frame_id,
            "payload_hex": payload.hex(),
            "is_fd": True,
            "bitrate_switch": True,
            "timestamp_format": "candump -L -N",
        },
        "authorization": {
            "reservation_mode": observer.mode,
            "reservation_authorized_to_transmit": observer.authorized_to_transmit,
            "plan_authorized_to_transmit": plan.authorized_to_transmit,
            "cansend_invoked": False,
            "peer_fixture": "python-can SocketCAN; test stimulus only, not CUTIL send authorization",
        },
        "hardware_qualification": "NOT_EVALUATED: vcan does not prove a physical controller, hardware timestamping, bus arbitration/load, or electrical behaviour.",
    }
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(json.dumps(report, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    return output


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--interface", default="can2")
    parser.add_argument("--channel-id", default="CANFD_2")
    parser.add_argument("--candump", type=Path, required=True)
    parser.add_argument("--contract-dir", type=Path, default=ROOT / "docs/interfaces/baseline")
    parser.add_argument("--expected-sha256", default=BASELINE_SHA256)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    print(run(args.interface, args.channel_id, args.candump, args.output, args.contract_dir,
              args.expected_sha256))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
