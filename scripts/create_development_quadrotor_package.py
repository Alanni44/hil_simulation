#!/usr/bin/env python3
"""Create a deterministic development-only quadrotor C model package.

This generator deliberately does *not* create a Simulink model or a release
asset.  The package is a bounded C ABI fixture for developing the 3.6 model
consumer and proving C-side input/readback plumbing before an approved ERT
package is available.  Its manifest is explicitly non-MATLAB, so the regular
MATLAB release builder rejects it.
"""

import argparse
import hashlib
import json
from pathlib import Path
import sys


ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))
if str(ROOT / "python_services") not in sys.path:
    sys.path.insert(0, str(ROOT / "python_services"))

from icd_runtime.contract import Contract
from shared.model_package import package_sha256, sha256_file, validate_package


BASELINE = "22163dc21526ceadd63260b3d5670404a1064c4301e52b2a80edcf41a4fe8a27"


README = """# Development-only quadrotor model package

This is a **DEVELOPMENT_ONLY** deterministic C fixture for the 3.6 ModelConsumer
bridge.  It is not generated by Simulink, is not an approved model package,
does not demonstrate real-time behavior, and must never be deployed to a HIL
target or used as evidence of aircraft/model validity.

`quadrotor_hil.slx` is an intentional non-Simulink sentinel.  The manifest's
`matlab_version` is `DEVELOPMENT_C_ABI_ONLY_NOT_MATLAB`, so the MATLAB release
builder will reject this package.  Compile only `development_quad_model.c`
with its public header for local consumer development.
"""


HEADER = r"""#ifndef DEVELOPMENT_QUAD_MODEL_H
#define DEVELOPMENT_QUAD_MODEL_H

#include <stdbool.h>

typedef struct {
    double motor_command[4];
    double wind_n_mps, wind_e_mps, wind_d_mps;
    double pressure_pa, temperature_k, ground_height_m;
    double gps_bias_n_m, gps_bias_e_m, gps_bias_d_m;
    double imu_bias_p_radps, imu_bias_q_radps, imu_bias_r_radps;
    bool motor_1_failed, motor_2_failed, motor_3_failed, motor_4_failed;
    double command_delay_ms, sensor_delay_ms, packet_loss_ratio;
} DevelopmentQuadU;

typedef struct {
    double north_m, east_m, down_m;
    double vn_mps, ve_mps, vd_mps;
    double q_w, q_x, q_y, q_z;
    double p_radps, q_radps, r_radps;
    bool airborne;
    double ax_mps2, ay_mps2, az_mps2;
} DevelopmentQuadY;

extern DevelopmentQuadU development_quad_U;
extern DevelopmentQuadY development_quad_Y;
extern double uav_mass_kg, uav_inertia_xx_kgm2, uav_inertia_yy_kgm2;
extern double uav_inertia_zz_kgm2, uav_thrust_coefficient_n;
extern double uav_moment_coefficient_nm, uav_linear_drag_ns_m;
extern double uav_angular_drag_nms, uav_wind_n_bias_mps;
extern double uav_wind_e_bias_mps, uav_wind_d_bias_mps, uav_motor_efficiency;

void development_quad_initialize(void);
void development_quad_step(void);
void development_quad_terminate(void);
DevelopmentQuadU *development_quad_get_input(void);
void development_quad_get_output(DevelopmentQuadY *out);
int development_quad_is_loaded(void);
void development_quad_read_motor_command(double out[4]);

#endif
"""


BRIDGE_HEADER = r"""#ifndef DEVELOPMENT_QUAD_MODEL_RT_BRIDGE_H
#define DEVELOPMENT_QUAD_MODEL_RT_BRIDGE_H

#include "development_quad_model.h"

typedef DevelopmentQuadU ModelU_t;
typedef DevelopmentQuadY ModelY_t;
#define MODEL_U_T_DEFINED 1
#define MODEL_Y_T_DEFINED 1
#define MODEL_INIT_FN development_quad_initialize
#define MODEL_STEP_FN development_quad_step
#define MODEL_TERM_FN development_quad_terminate
#define MODEL_U_VAR development_quad_U
#define MODEL_Y_VAR development_quad_Y

#endif
"""


SOURCE = r"""#include "development_quad_model.h"

#include <math.h>
#include <string.h>

#define DT 0.001
#define GRAVITY 9.80665

DevelopmentQuadU development_quad_U;
DevelopmentQuadY development_quad_Y;
double uav_mass_kg = 1.5;
double uav_inertia_xx_kgm2 = 0.029;
double uav_inertia_yy_kgm2 = 0.029;
double uav_inertia_zz_kgm2 = 0.055;
double uav_thrust_coefficient_n = 4.2;
double uav_moment_coefficient_nm = 0.08;
double uav_linear_drag_ns_m = 0.25;
double uav_angular_drag_nms = 0.02;
double uav_wind_n_bias_mps = 0.0;
double uav_wind_e_bias_mps = 0.0;
double uav_wind_d_bias_mps = 0.0;
double uav_motor_efficiency = 1.0;
static int loaded = 0;

static double enabled_motor(unsigned index) {
    const bool failed[4] = {development_quad_U.motor_1_failed, development_quad_U.motor_2_failed,
                            development_quad_U.motor_3_failed, development_quad_U.motor_4_failed};
    return failed[index] ? 0.0 : development_quad_U.motor_command[index];
}

void development_quad_initialize(void) {
    memset(&development_quad_U, 0, sizeof(development_quad_U));
    memset(&development_quad_Y, 0, sizeof(development_quad_Y));
    development_quad_U.pressure_pa = 101325.0;
    development_quad_U.temperature_k = 288.15;
    development_quad_Y.q_w = 1.0;
    loaded = 1;
}

void development_quad_step(void) {
    double m[4], thrust = 0.0, roll_torque, pitch_torque, yaw_torque;
    double wind_n, wind_e, wind_d, mass;
    unsigned index;
    if (!loaded) return;
    for (index = 0; index < 4; ++index) {
        m[index] = enabled_motor(index);
        thrust += uav_thrust_coefficient_n * uav_motor_efficiency * m[index] * m[index];
    }
    mass = uav_mass_kg;
    wind_n = development_quad_U.wind_n_mps + uav_wind_n_bias_mps;
    wind_e = development_quad_U.wind_e_mps + uav_wind_e_bias_mps;
    wind_d = development_quad_U.wind_d_mps + uav_wind_d_bias_mps;
    development_quad_Y.ax_mps2 = -uav_linear_drag_ns_m * (development_quad_Y.vn_mps - wind_n) / mass;
    development_quad_Y.ay_mps2 = -uav_linear_drag_ns_m * (development_quad_Y.ve_mps - wind_e) / mass;
    development_quad_Y.az_mps2 = GRAVITY - thrust / mass
        - uav_linear_drag_ns_m * (development_quad_Y.vd_mps - wind_d) / mass;
    roll_torque = (m[0] - m[1] - m[2] + m[3]) * uav_moment_coefficient_nm;
    pitch_torque = (m[0] + m[1] - m[2] - m[3]) * uav_moment_coefficient_nm;
    yaw_torque = (m[0] - m[1] + m[2] - m[3]) * uav_moment_coefficient_nm;
    development_quad_Y.p_radps += DT * (roll_torque / uav_inertia_xx_kgm2
        - uav_angular_drag_nms * development_quad_Y.p_radps / uav_inertia_xx_kgm2);
    development_quad_Y.q_radps += DT * (pitch_torque / uav_inertia_yy_kgm2
        - uav_angular_drag_nms * development_quad_Y.q_radps / uav_inertia_yy_kgm2);
    development_quad_Y.r_radps += DT * (yaw_torque / uav_inertia_zz_kgm2
        - uav_angular_drag_nms * development_quad_Y.r_radps / uav_inertia_zz_kgm2);
    development_quad_Y.vn_mps += DT * development_quad_Y.ax_mps2;
    development_quad_Y.ve_mps += DT * development_quad_Y.ay_mps2;
    development_quad_Y.vd_mps += DT * development_quad_Y.az_mps2;
    development_quad_Y.north_m += DT * development_quad_Y.vn_mps + development_quad_U.gps_bias_n_m;
    development_quad_Y.east_m += DT * development_quad_Y.ve_mps + development_quad_U.gps_bias_e_m;
    development_quad_Y.down_m += DT * development_quad_Y.vd_mps + development_quad_U.gps_bias_d_m;
    development_quad_Y.airborne = development_quad_Y.down_m < development_quad_U.ground_height_m - 0.001;
}

void development_quad_terminate(void) { loaded = 0; }
DevelopmentQuadU *development_quad_get_input(void) { return &development_quad_U; }
void development_quad_get_output(DevelopmentQuadY *out) { if (out) *out = development_quad_Y; }
int development_quad_is_loaded(void) { return loaded; }
void development_quad_read_motor_command(double out[4]) {
    if (out) memcpy(out, development_quad_U.motor_command, sizeof(development_quad_U.motor_command));
}
"""


def _runtime_contract(contract):
    rows = [row for row in contract.catalogue["model_bindings"] if row["model_id"] == "quadrotor_hil"]
    result = {"contract_version": 3, "model_name": "quadrotor_hil", "vehicle_kind": "multirotor",
              "control_sources": ["demo_mission", "px4_sitl", "physical_uut"],
              "sensors": {"imu": {"rate_hz": 250}, "gps": {"rate_hz": 20},
                          "magnetometer": {"rate_hz": 50}, "barometer": {"rate_hz": 50}},
              "state": {"frame": "NED", "orientation": "FRD_TO_NED_QUATERNION",
                        "outputs": {name: name for name in ("north_m", "east_m", "down_m", "vn_mps", "ve_mps", "vd_mps", "q_w", "q_x", "q_y", "q_z", "p_radps", "q_radps", "r_radps", "airborne")},
                        "units": {"north_m": "m", "east_m": "m", "down_m": "m", "vn_mps": "m/s", "ve_mps": "m/s", "vd_mps": "m/s", "q_w": "1", "q_x": "1", "q_y": "1", "q_z": "1", "p_radps": "rad/s", "q_radps": "rad/s", "r_radps": "rad/s", "airborne": "bool"}},
              "inputs": {"flight_control": {"mode": "motor_command", "ports": {}},
                         "environment": {"ports": {}}, "fault": {"ports": {}}},
              "outputs": {"internal_state": {"rate_hz": 50, "consumer": "c_python_only",
                         "include_in_ue4_json": False, "acceleration": {
                             name: {"field": name, "unit": "m/s2", "type": "double", "dimension": 1, "min": -200.0, "max": 200.0}
                             for name in ("ax_mps2", "ay_mps2", "az_mps2")}}},
              "execution": {"step_s": 0.001, "locked_configuration": ["solver_step_s", "model_topology", "port_schema", "communication_endpoint"]},
              "actuators": {"channels": []}, "parameters": []}
    for row in rows:
        group, name = row["path"].split(".")
        if group == "parameters":
            result["parameters"].append({"name": name, "generated_field": row["target_field"],
                "type": row["type"], "unit": row["unit"], "default": row["default"], "min": row["min"], "max": row["max"],
                "class": "live", "allowed_phases": ["RUNNING", "PAUSED"],
                "binding": {"kind": "exported_global", "symbol": row["target_field"]}})
            continue
        descriptor = {key: row[key] for key in ("target_field", "type", "unit", "dimension", "min", "max")}
        descriptor["field"] = descriptor.pop("target_field")
        if group == "environment": descriptor["default"] = row["default"]
        result["inputs"][group]["ports"][name] = descriptor
    for index in range(4):
        result["actuators"]["channels"].append({"name": "motor_{:02d}".format(index + 1), "unit": "1",
            "min": 0.0, "max": 1.0, "safe_value": 0.0,
            "binding": {"input": "flight_control.motor_command", "index": index}})
    return result


def create(output, contract_dir, expected_sha256):
    output = Path(output)
    if output.exists():
        raise FileExistsError("development package output must not already exist")
    contract = Contract.load(contract_dir, expected_sha256=expected_sha256)
    package = _runtime_contract(contract)
    output.mkdir(parents=True)
    files = {"README.md": README, "quadrotor_hil.slx": "DEVELOPMENT_ONLY_NOT_A_SIMULINK_MODEL\n",
             "hil_contract.json": json.dumps(package, ensure_ascii=True, sort_keys=True, indent=2) + "\n",
             "development_quad_model.h": HEADER, "model_rt_bridge.h": BRIDGE_HEADER,
             "development_quad_model.c": SOURCE}
    for name, value in files.items():
        (output / name).write_text(value, encoding="utf-8")
    manifest = {"model_ref": "DEVELOPMENT_ONLY_NOT_RELEASE", "model_revision_ref": "development-quad-v1",
                "top_model": "quadrotor_hil.slx", "matlab_version": "DEVELOPMENT_C_ABI_ONLY_NOT_MATLAB",
                "files": {name: sha256_file(output / name) for name in sorted(files)}, "dependencies": [],
                "package_sha256": package_sha256(output)}
    (output / "package_manifest.json").write_text(json.dumps(manifest, ensure_ascii=True, sort_keys=True, indent=2) + "\n", encoding="utf-8")
    checked = validate_package(output, output.parent, manifest["package_sha256"])
    return {"output": str(output.resolve()), "package_sha256": checked["package_sha256"],
            "contract_sha256": checked["contract_sha256"], "development_only": True,
            "model_application_qualified": False}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--contract-dir", type=Path, default=Path("docs/interfaces/baseline"))
    parser.add_argument("--expected-sha256", default=BASELINE)
    args = parser.parse_args()
    try:
        print(json.dumps(create(args.output, args.contract_dir, args.expected_sha256), ensure_ascii=True))
        return 0
    except (OSError, ValueError) as error:
        print(json.dumps({"status": "FAILED", "detail": str(error), "development_only": True}))
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
